import * as path from 'path';
import * as vscode from 'vscode';
import { CoverageStore } from './coverageStore';
import { formatPercent, percent } from './lcov';
import { levelFor } from './thresholds';
import { trendText } from './treeProvider';

/** A shields-style badge drawn locally, so it works offline and in private repos. */
export function badgeSvg(label: string, value: string, color: string): string {
  const w = (s: string) => Math.round(s.length * 6.6 + 12);
  const lw = w(label);
  const vw = w(value);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${lw + vw}" height="20" role="img" aria-label="${label}: ${value}">
<linearGradient id="s" x2="0" y2="100%"><stop offset="0" stop-color="#bbb" stop-opacity=".1"/><stop offset="1" stop-opacity=".1"/></linearGradient>
<clipPath id="r"><rect width="${lw + vw}" height="20" rx="3" fill="#fff"/></clipPath>
<g clip-path="url(#r)"><rect width="${lw}" height="20" fill="#555"/><rect x="${lw}" width="${vw}" height="20" fill="${color}"/><rect width="${lw + vw}" height="20" fill="url(#s)"/></g>
<g fill="#fff" text-anchor="middle" font-family="Verdana,Geneva,DejaVu Sans,sans-serif" font-size="11">
<text x="${lw / 2}" y="15" fill="#010101" fill-opacity=".3">${label}</text><text x="${lw / 2}" y="14">${label}</text>
<text x="${lw + vw / 2}" y="15" fill="#010101" fill-opacity=".3">${value}</text><text x="${lw + vw / 2}" y="14">${value}</text>
</g></svg>
`;
}

export function markdownSummary(store: CoverageStore): string {
  const totals = store.totals();
  const pct = percent(totals.linesHit, totals.linesFound);
  const goal = vscode.workspace.getConfiguration('dartboard').get<number>('goal', 80);
  const trend = store.totalTrendDelta;
  const lines: string[] = [];
  lines.push(`### 🧪 Test coverage: ${formatPercent(pct)}${trend !== undefined ? ` (${trendText(trend)})` : ''}`);
  lines.push('');
  lines.push(`${totals.linesHit} of ${totals.linesFound} lines covered${goal ? ` · goal ${goal}% ${pct !== undefined && pct >= goal ? '✅' : '⏳'}` : ''}`);
  const changed = store.all().filter((f) => store.isChanged(f));
  const rows = (changed.length ? changed : store.all())
    .map((f) => ({ f, p: percent(f.linesHit, f.linesFound) ?? 100 }))
    .sort((a, b) => a.p - b.p)
    .slice(0, 15);
  lines.push('');
  lines.push(changed.length ? '**Files changed on this branch**' : '**Least covered files**');
  lines.push('');
  lines.push('| File | Coverage | Lines |');
  lines.push('| --- | ---: | ---: |');
  for (const { f, p } of rows) {
    const icon = f.untested ? '⚪' : levelFor(p) === 'high' ? '🟢' : levelFor(p) === 'medium' ? '🟡' : '🔴';
    const t = store.trend(f);
    lines.push(`| ${icon} \`${f.relativePath}\` | ${f.untested ? 'no tests' : formatPercent(p)}${t !== undefined ? ` ${trendText(t)}` : ''} | ${f.linesHit}/${f.linesFound} |`);
  }
  const untested = store.untested().length;
  if (untested) {
    lines.push('');
    lines.push(`_${untested} file(s) in lib/ have no tests at all._`);
  }
  lines.push('');
  lines.push('<sub>Generated by Dartboard</sub>');
  return lines.join('\n');
}

export async function share(store: CoverageStore): Promise<void> {
  if (!store.hasData) {
    void vscode.window.showInformationMessage('Run coverage first.');
    return;
  }
  const pick = await vscode.window.showQuickPick(
    [
      { id: 'md', label: '$(markdown) Copy summary for a pull request', detail: 'A Markdown table with the total, trend and least covered (or changed) files.' },
      { id: 'badge', label: '$(verified) Save a coverage badge for your README', detail: 'Writes coverage/coverage_badge.svg locally and copies the Markdown to show it.' },
    ],
    { placeHolder: 'Share coverage' },
  );
  if (!pick) {
    return;
  }
  if (pick.id === 'md') {
    await vscode.env.clipboard.writeText(markdownSummary(store));
    void vscode.window.showInformationMessage('Coverage summary copied. Paste it into your PR description.');
    return;
  }
  const totals = store.totals();
  const pct = percent(totals.linesHit, totals.linesFound);
  const level = levelFor(pct);
  const color = level === 'high' ? '#2ea043' : level === 'medium' ? '#d29922' : '#e5534b';
  const report = store.reportUris[0];
  const dir = path.dirname(report.fsPath);
  const target = vscode.Uri.file(path.join(dir, 'coverage_badge.svg'));
  await vscode.workspace.fs.writeFile(target, Buffer.from(badgeSvg('coverage', formatPercent(pct), color), 'utf8'));
  const folder = vscode.workspace.getWorkspaceFolder(target);
  const rel = folder ? path.relative(folder.uri.fsPath, target.fsPath).split(path.sep).join('/') : target.fsPath;
  await vscode.env.clipboard.writeText(`![coverage](${rel})`);
  void vscode.window.showInformationMessage(
    `Badge saved to ${rel} and the Markdown copied. Commit the badge (coverage/ is often git-ignored, so you may need to move it) and paste the Markdown into your README.`,
  );
}
